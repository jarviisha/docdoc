"""The walk that turns labels and predictions into outcomes.

For each document in the golden set, every label resolves to exactly one member of
the closed set, every predicted path the golden set does not label becomes
``UNLABELED``, and a document with no prediction at all becomes ``UNEVALUATED``.

The three cases that decide whether this feature is honest:

**A document with no prediction is ``UNEVALUATED`` and stays in every
denominator** (FR-005). Dropping it is how a crash becomes an accuracy
improvement.

**A document that failed mid-pipeline has its labelled fields counted as
``MISSING``** (FR-037), not excluded. Same reason, one step further along: failing
on the hard documents must not be able to raise a score.

**A value that is correct but ungrounded is ``CORRECT``** (FR-027). Correctness
and groundedness are independent facts measured separately; merging them would let
a grounding failure masquerade as an extraction failure.
"""

from __future__ import annotations

import re
from typing import TYPE_CHECKING, Any

from docdoc.evaluation.alignment import GroupOutcome, align
from docdoc.evaluation.comparators import comparator_version_for, equal
from docdoc.evaluation.labels import Expectation
from docdoc.evaluation.location import agreement_for
from docdoc.evaluation.ordering import path_key
from docdoc.evaluation.outcomes import FieldOutcome, FieldOutcomeKind
from docdoc.evaluation.redact import redact_outcome
from docdoc.evaluation.values import strip_indices

if TYPE_CHECKING:
    from collections.abc import Callable, Sequence

    from docdoc.evaluation.golden import GoldenDocument, GoldenSet
    from docdoc.evaluation.labels import Label
    from docdoc.evaluation.predictions import DocumentPrediction
    from docdoc.extraction.value import ExtractedValue
    from docdoc.grounding.result import GroundingOutcome

__all__ = ["outcome_sort_key", "score_document"]

#: A repeating-group entry reference: the group path, the entry index, and the
#: rest of the path inside that entry. Paths are generated by docdoc itself
#: (``extraction/conform.py`` builds ``f"{path}[{index}]."``), never authored in a
#: document, so this parses a known form rather than untrusted text.
_ENTRY = re.compile(r"^(?P<group>[^\[\]]+)\[(?P<index>\d+)\](?:\.(?P<rest>.+))?$")


def outcome_sort_key(outcome: FieldOutcome) -> tuple[Any, ...]:
    """The total order of EVA-26: ``(tier, document_id, path_key, field_path)``.

    ``field_path`` is the final tie-break so the order stays total even if two
    distinct paths ever decompose identically.
    """
    return (
        str(outcome.tier),
        outcome.document_id,
        path_key(outcome.field_path),
        outcome.field_path,
    )


def _render(value: Any) -> str | None:
    """A canonical rendering, so two runs produce the same text for one fact."""
    if value is None:
        return None
    if isinstance(value, str):
        return value
    return str(value)


def _predicted_values(prediction: DocumentPrediction) -> dict[str, ExtractedValue]:
    """Every scalar the extraction recorded, keyed by field path.

    Walks the value tree the same way `conform` built it, so the paths here are
    the paths a label addresses (FR-017).
    """
    if prediction.extraction is None:
        return {}
    found: dict[str, ExtractedValue] = {}
    _walk(prediction.extraction.values, "", found)
    return found


def _walk(node: Any, prefix: str, found: dict[str, ExtractedValue]) -> None:
    if isinstance(node, dict):
        for name, child in node.items():
            _walk(child, f"{prefix}{name}" if not prefix else f"{prefix}.{name}", found)
        return
    if isinstance(node, (list, tuple)):
        for index, child in enumerate(node):
            _walk(child, f"{prefix}[{index}]", found)
        return
    if hasattr(node, "field_path"):
        found[node.field_path] = node


def _grounding_outcome(prediction: DocumentPrediction, field_path: str) -> GroundingOutcome | None:
    if prediction.grounding is None:
        return None
    return prediction.grounding.outcomes.get(field_path)


def _classify(
    label: Label,
    predicted: ExtractedValue | None,
    *,
    failed: bool,
) -> tuple[FieldOutcomeKind, Any, Any]:
    """Resolve one label against one prediction to exactly one closed outcome."""
    if label.expectation is Expectation.VALUE:
        if failed or predicted is None or not predicted.present:
            return FieldOutcomeKind.MISSING, label.value, None
        if equal(label.value, predicted.value):
            return FieldOutcomeKind.CORRECT, label.value, predicted.value
        return FieldOutcomeKind.INCORRECT, label.value, predicted.value

    # An absence label. A failed document did not assert anything, so it cannot
    # have invented a value: absence is trivially satisfied and counted correct.
    if failed or predicted is None or not predicted.present:
        return FieldOutcomeKind.CORRECT, None, None
    return FieldOutcomeKind.SPURIOUS, None, predicted.value


def _split_entry(field_path: str) -> tuple[str, int, str] | None:
    """``line_items[2].amount`` -> ``("line_items", 2, "amount")``, else ``None``."""
    match = _ENTRY.match(field_path)
    if match is None:
        return None
    return match["group"], int(match["index"]), match["rest"] or ""


def _entry_counts(paths: Sequence[str]) -> dict[str, int]:
    """How many entries each repeating group has, by highest index seen.

    Read from the paths themselves rather than from the value tree's shape,
    because the two sides arrive differently: labels are a flat list of paths and
    a prediction is a nested tree, and this is the one form both can produce.
    """
    counts: dict[str, int] = {}
    for path in paths:
        parsed = _split_entry(path)
        if parsed is None:
            continue
        group, index, _ = parsed
        counts[group] = max(counts.get(group, 0), index + 1)
    return counts


def _keys_for(
    group: str,
    entries: int,
    key_field: str | None,
    lookup: Callable[[str], Any],
) -> list[Any]:
    """The alignment key of each entry, or its index when no key is declared.

    Falling back to the index is not a second alignment policy -- ``align``
    ignores these values entirely under ``positional@1`` and reads only their
    count. It is here so the two callers can share one shape.
    """
    if key_field is None:
        return list(range(entries))
    return [lookup(f"{group}[{index}].{key_field}") for index in range(entries)]


def _align_groups(
    *,
    document_id: str,
    labels: Sequence[Label],
    predicted_values: dict[str, ExtractedValue],
    key_for: Callable[[str], str | None] | None,
) -> tuple[dict[str, dict[int, int | None]], tuple[GroupOutcome, ...]]:
    """Decide which predicted entry each expected entry is compared against.

    Returns the expected-index -> predicted-index map per group, and the group's
    own reported facts. The second half is FR-021: an entry-count mismatch is
    reported as **its own fact**, because positional alignment downstream of a
    missing entry shifts every later entry by one and produces field-level
    wreckage that reads as many independent errors when it is one.
    """
    expected_counts = _entry_counts([label.field_path for label in labels])
    predicted_counts = _entry_counts(list(predicted_values))

    label_values = {label.field_path: label.value for label in labels}
    mapping: dict[str, dict[int, int | None]] = {}
    group_outcomes: list[GroupOutcome] = []

    for group in sorted(set(expected_counts) | set(predicted_counts)):
        key_field = key_for(group) if key_for is not None else None
        expected_entries = expected_counts.get(group, 0)
        predicted_entries = predicted_counts.get(group, 0)

        pairs, outcome = align(
            document_id=document_id,
            group_path=group,
            expected_keys=_keys_for(group, expected_entries, key_field, label_values.get),
            predicted_keys=_keys_for(
                group,
                predicted_entries,
                key_field,
                lambda path: getattr(predicted_values.get(path), "value", None),
            ),
            key_field=key_field,
        )
        mapping[group] = {
            expected: predicted for expected, predicted in pairs if expected is not None
        }
        group_outcomes.append(outcome)

    return mapping, tuple(group_outcomes)


def _compared_path(field_path: str, mapping: dict[str, dict[int, int | None]]) -> str | None:
    """Where in the prediction a label's expected entry actually landed.

    ``None`` when alignment matched the expected entry to nothing -- a missing
    entry, whose fields are missing values rather than fields compared against
    whatever happened to sit at the same index.
    """
    parsed = _split_entry(field_path)
    if parsed is None:
        return field_path
    group, index, rest = parsed
    predicted_index = mapping.get(group, {}).get(index, index)
    if predicted_index is None:
        return None
    return f"{group}[{predicted_index}]" + (f".{rest}" if rest else "")


def score_document(
    document: GoldenDocument,
    labels: Sequence[Label],
    prediction: DocumentPrediction | None,
    *,
    field_type_for: dict[str, Any] | None = None,
    key_for: Callable[[str], str | None] | None = None,
) -> tuple[tuple[FieldOutcome, ...], tuple[GroupOutcome, ...]]:
    """Every outcome for one document, plus its repeating groups' own facts.

    Returned unordered: ordering is a property of the report, not of a document,
    so the caller sorts (EVA-26).
    """
    types = field_type_for or {}

    if prediction is None:
        # No prediction at all. Named, counted, and in every denominator -- the
        # distinction from a *failed* document is real and both are reported.
        return (
            tuple(
                redact_outcome(
                    FieldOutcome(
                        document_id=document.document_id,
                        field_path=label.field_path,
                        kind=FieldOutcomeKind.UNEVALUATED,
                        tier=document.tier,
                        expected=_render(label.value),
                    )
                )
                for label in labels
            ),
            (),
        )

    failed = not prediction.processed
    predicted_values = _predicted_values(prediction)
    mapping, group_outcomes = _align_groups(
        document_id=document.document_id,
        labels=labels,
        predicted_values=predicted_values,
        key_for=key_for,
    )

    outcomes: list[FieldOutcome] = []
    consumed: set[str] = set()

    for label in labels:
        compared_path = _compared_path(label.field_path, mapping)
        predicted = None if compared_path is None else predicted_values.get(compared_path)
        if compared_path is not None:
            consumed.add(compared_path)
        kind, expected_value, predicted_value = _classify(label, predicted, failed=failed)
        # Grounding is read from where the value actually was, not from where the
        # label says it should be: a shifted entry is still grounded, and
        # reporting it as ungrounded would charge one alignment failure twice.
        grounding = _grounding_outcome(prediction, compared_path or label.field_path)

        outcomes.append(
            redact_outcome(
                FieldOutcome(
                    document_id=document.document_id,
                    field_path=label.field_path,
                    kind=kind,
                    tier=document.tier,
                    expected=None if kind is FieldOutcomeKind.CORRECT else _render(expected_value),
                    predicted=None
                    if kind is FieldOutcomeKind.CORRECT
                    else _render(predicted_value),
                    comparator_version=comparator_version_for(
                        types.get(strip_indices(label.field_path))
                    ),
                    grounding_status=None if grounding is None else grounding.status,
                    grounding_score=None if grounding is None else grounding.score,
                    location_agreement=agreement_for(label.location, grounding),
                )
            )
        )

    # Predicted paths the golden set says nothing about -- including every field
    # of a spurious entry. Counted and reported, and in no accuracy denominator
    # (FR-036, EVA-8b).
    #
    # **Nothing is reported for a document that failed.** Its labelled fields are
    # already MISSING, and reporting the values its half-finished extraction
    # happened to hold would have the report say two contradictory things about
    # one artifact: that this document produced nothing where a label exists, and
    # that it produced a value where none does. It would also make the
    # ``unlabeled`` count a function of how far a crash got before it stopped.
    for field_path, value in () if failed else predicted_values.items():
        if field_path in consumed or not value.present:
            continue
        grounding = _grounding_outcome(prediction, field_path)
        outcomes.append(
            redact_outcome(
                FieldOutcome(
                    document_id=document.document_id,
                    field_path=field_path,
                    kind=FieldOutcomeKind.UNLABELED,
                    tier=document.tier,
                    predicted=_render(value.value),
                    grounding_status=None if grounding is None else grounding.status,
                    grounding_score=None if grounding is None else grounding.score,
                )
            )
        )

    return tuple(outcomes), group_outcomes


def value_path_index(golden: GoldenSet) -> set[tuple[str, str]]:
    """``(document_id, field_path)`` for every label stating a value.

    The V partition of EVA-17. ``CORRECT`` and ``UNEVALUATED`` occur in both V and
    A with different denominators, so counting needs to know which partition each
    outcome belongs to.
    """
    return {
        (document_id, label.field_path)
        for document_id, labels in golden.labels.items()
        for label in labels
        if label.expectation is Expectation.VALUE
    }
