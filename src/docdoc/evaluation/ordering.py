"""The total order a report's outcomes are emitted in (EVA-26).

FR-043 requires a report to be byte-identical on every run and every platform, and
"identical" is only meaningful if the ordering is total. Two hazards make that
non-trivial, and both have bitten this repository before:

**Lexicographic ordering puts ``[10]`` before ``[2]``.** Milestone 5 hit this and
solved it by carrying the entry index separately from the check id. The hazard is
identical here, so entry indices are typed as integers rather than compared as
text.

**Dict and set iteration order varies with ``PYTHONHASHSEED``.** A single-seeded
suite passes a hash-order dependency by luck, which is why CI runs a second seed.
Nothing here iterates a set to produce order; the key below is the whole story.

**Why Milestone 5's ``sort_key`` is not reused.** ``validation.verdict.sort_key``
orders by the enumeration walk's position -- that is, by schema declaration order
-- which is the right answer for a result produced under exactly one schema. A
golden set spans schemas by requirement (FR-013), so there is no single
declaration order to appeal to, and no walk has been run: this layer reads
recorded facts and never re-derives them. What is reused is the lesson, not the
function.
"""

from __future__ import annotations

import re
from functools import lru_cache

__all__ = ["PathKey", "path_key"]

#: One field-path segment: a name, or a bracketed entry index. The paths this
#: parses were generated by docdoc itself (``extraction/conform.py`` builds
#: ``f"{path}[{index}]."``), never authored by a user and never read out of a
#: document, so this is not a pattern-injection surface the way Milestone 5's
#: authored patterns were.
_SEGMENT = re.compile(r"([^.\[\]]+)|\[(\d+)\]")

#: A name segment sorts as ``(1, name, 0)``, an index as ``(0, "", index)``. The
#: leading discriminator keeps the tuple types uniform so Python never compares a
#: ``str`` against an ``int`` and raises at sort time.
PathKey = tuple[tuple[int, str, int], ...]


@lru_cache(maxsize=4096)
def path_key(field_path: str) -> PathKey:
    """Decompose a field path so entry 2 sorts before entry 10.

    ``"line_items[10].amount"`` becomes
    ``((1, "line_items", 0), (0, "", 10), (1, "amount", 0))``.

    Cached because the decomposition costs ~1.85 µs measured, which is ~0.93 ms
    per 500 labelled fields if recomputed per comparison -- half the entire
    scoring budget spent on parsing strings the caller already holds.
    """
    segments: list[tuple[int, str, int]] = []
    for name, index in _SEGMENT.findall(field_path):
        if index:
            segments.append((0, "", int(index)))
        else:
            segments.append((1, name, 0))
    return tuple(segments)
